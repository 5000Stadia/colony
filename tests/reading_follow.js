const assert = require('node:assert/strict'), vm = require('node:vm');
const source = require('node:fs').readFileSync(0, 'utf8');
const start = source.indexOf('  const readingFollow = window.colonyReadingFollow ='), end = source.indexOf('  const fresh =', start);
assert(start > 0 && end > start);
let time = 10000, chatting = true;
const stops = [], listeners = new Map();
const window = {scrollX: 0, scrollY: 40, scrollTo: (how) => stops.push(how)}, document = {getElementById: () => chatting ? {} : null};
vm.runInNewContext(source.slice(start, end), {window, document, O: {add: {call(_window, type, listener) { listeners.set(type, listener); }}}, Date: {now: () => time}});
const follow = window.colonyReadingFollow;
const emit = (type, extra = {}) => listeners.get(type)({type, isTrusted: true, ...extra});
// no clock is kept any more: whether the page follows is the person's switch, in the player
assert.deepEqual(Object.keys(follow).sort(), ['inChat', 'programmatic']);
assert(follow.inChat()); chatting = false; assert(!follow.inChat()); chatting = true;
emit('touchstart'); assert.equal(stops.length, 0, 'a touch with no reading scroll under way stops nothing');
follow.programmatic(() => {}); emit('pointermove', {buttons: 0, pointerType: 'mouse'}); assert.equal(stops.length, 0, 'hover is not a touch');
emit('wheel', {isTrusted: false}); assert.equal(stops.length, 0, 'a made-up event is not the person');
emit('pointerdown', {target: {closest: (sel) => sel === '#cplayer'}}); assert.equal(stops.length, 0, "the player's own controls leave the reading's scroll alone");
emit('touchmove'); assert.equal(JSON.stringify(stops), JSON.stringify([{left: 0, top: 40, behavior: 'instant'}]), 'a finger stops the scroll the reading began');
emit('touchmove'); assert.equal(stops.length, 1, 'once');
follow.programmatic(() => {}); time += 1001; emit('wheel'); assert.equal(stops.length, 1, 'a reading scroll long done is not stopped');
console.log('PASS production reading-follow clock');
